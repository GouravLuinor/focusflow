from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session, joinedload

from app.db.deps import get_db
from app.core.auth import get_current_user
from app.models.profile import NeuroProfile
from app.models.task import Task
from app.models.step import Step
from app.services.ai_service import generate_ai_steps

router = APIRouter(prefix="/ai", tags=["ai"])


@router.post("/generate-steps")
def ai_generate_steps(
    title: str,
    db: Session = Depends(get_db),
    user=Depends(get_current_user),
):

    # 1️⃣ Get user's support mode
    profile = (
        db.query(NeuroProfile)
        .filter(NeuroProfile.user_id == user.id)
        .first()
    )

    support_mode = profile.support_mode if profile else "adhd"

    # 2️⃣ Generate AI steps
    steps = generate_ai_steps(title, support_mode)

    # 3️⃣ Create Task
    task = Task(
        title=title,
        description="Generated by AI",
        user_id=user.id,
        is_completed=False,
    )

    db.add(task)
    db.commit()
    db.refresh(task)

    # 4️⃣ Create Step records
    for index, step_text in enumerate(steps):
        step = Step(
            content=step_text,
            order=index + 1,
            task_id=task.id,
            is_completed=False,
        )
        db.add(step)

    db.commit()

    # 5️⃣ Reload task WITH steps (important)
    task_with_steps = (
        db.query(Task)
        .options(joinedload(Task.steps))
        .filter(Task.id == task.id)
        .first()
    )

    return task_with_steps


from pydantic import BaseModel, Field
from fastapi import HTTPException
from fastapi.concurrency import run_in_threadpool
from app.services.ai_service import parse_task_text, AIUnavailableError, AIRequestError


class ParseTaskRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=1000)


@router.post("/parse-task")
async def parse_task_text_endpoint(request: ParseTaskRequest, current_user=Depends(get_current_user)):
    """Use Gemini to parse natural language into structured task data."""
    try:
        # Gemini call is blocking; keep it off the event loop.
        return await run_in_threadpool(parse_task_text, request.text)
    except AIUnavailableError:
        raise HTTPException(status_code=503, detail="AI service not available")
    except AIRequestError:
        raise HTTPException(status_code=502, detail="AI parsing failed. Please try again.")
